const LIST = COUNTRIES.map(([code, name]) => ({ code, name }));
const BY_CODE = new Map(LIST.map((c) => [c.code, c.name]));

export function countries(): { code: string; name: string }[] {
  return LIST;
}

export function countryName(code: string | null | undefined): string | null {
  if (!code) return null;
  return BY_CODE.get(code.toUpperCase()) ?? null;
}

export const isCountryCode = (v: string) => BY_CODE.has(v.toUpperCase());

